seen = set(); deduped = []
for r in rows:
    key = (r["BankAccount"], r["Ref"])
    if r["Ref"] and key in seen:
        continue
    seen.add(key); deduped.append(r)

# write CSV (only KEPT = non-interbank rows go to Daily Transactions)
header = ["Date","Value Date","Bank Account","Narration","Party Name","Mode",
          "Reference No","Type","Debit","Credit","Balance","Auto Tag",
          "Inter-Bank Excluded?","Source Email Date","Processed On"]
out = "/tmp/bs/daily_transactions.csv"
with open(out,"w",newline="") as f:
    w = csv.writer(f); w.writerow(header)
    for r in deduped:
        if r["InterBank"] == "YES":
            continue
        w.writerow([r["Date"],r["ValueDate"],r["BankAccount"],r["Narration"],r["Party"],
            r["Mode"],r["Ref"],r["Type"],r["Debit"],r["Credit"],r["Balance"],
            r["AutoTag"],r["InterBank"],r["SrcEmail"],r["Processed"]])

# summary
def s(x): return float(x) if x else 0.0
kept=[r for r in deduped if r["InterBank"]=="NO"]
excl=[r for r in deduped if r["InterBank"]=="YES"]
rcpt=sum(s(r["Credit"]) for r in kept)
paid=sum(s(r["Debit"]) for r in kept)
print("Total parsed rows:", len(rows), "| after dedup:", len(deduped))
print("KEPT (external):", len(kept), "| EXCLUDED inter-bank:", len(excl))
print("Receipts (Credit) kept: %0.2f" % rcpt)
print("Payments (Debit) kept:  %0.2f" % paid)
print("--- Inter-bank excluded ---")
for r in excl:
    amt = r["Debit"] or r["Credit"]
    print(f'  {r["BankAccount"]} {r["Type"]:7} {amt:>15} {r["Narration"][:55]}')
