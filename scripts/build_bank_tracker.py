# ISPL own-account markers for inter-bank exclusion
OWN_NAME = re.compile(r"IMPRESSIONS SERVICES", re.I)

def mode_of(narr):
    n = narr.upper()
    if n.startswith("EZY/ICICIPOS") or "ICICIPOS" in n: return "POS"
    if "RTGS" in n: return "RTGS"
    if "IMPS" in n or "MMT/IMPS" in n: return "IMPS"
    if "NEFT" in n: return "NEFT"
    if n.startswith("INF/INFT") or "INFT" in n: return "INFT"
    if n.startswith("CLG") or "IWCLG" in n or "/CLG" in n: return "CHQ"
    if n.startswith("CMS"): return "CMS"
    if n.startswith("TRF"): return "TRF"
    return "OTHER"

def classify(narr, ttype):
    n = narr.upper()
    if "PAYROLL" in n or "SALARY" in n: return "Payroll / Statutory"
    if any(k in n for k in ["ESI", "EPF", "PF "]): return "Payroll / Statutory"
    if any(k in n for k in ["GST", "TDS", "IT DEPT", "INCOME TAX"]): return "Tax Payment"
    if any(k in n for k in ["RENT", "LEASE"]): return "Rent"
    if any(k in n for k in ["INT CHRG", "INTEREST", "BANK CHARGE", "CHRG", "CHARGES"]): return "Bank Charges"
    if "INSURANCE" in n or "LOMBARD" in n: return "Vendor Payment"
    if mode_of(narr) == "POS": return "Client Receipt"
    if ttype == "RECEIPT":
        if mode_of(narr) == "CMS": return "CMS Collection"
        return "Client Receipt"
    # payments
    if mode_of(narr) == "CMS": return "CMS Settlement / Review Required"
    return "Review Required"

def is_interbank(narr):
    n = narr.upper()
    # ISPL own name appearing as the transferring/receiving party
    if OWN_NAME.search(n):
        return True
    # internal funding sweeps
    if re.search(r"\bFUND\d", n) or "FUND120626" in n or "FUND130626" in n:
        return True
    return False

def party_neft(narr):
    # NEFT-<BANKREF>-<PARTY>-... ; party is the segment after first ref
    parts = narr.split("-")
    if len(parts) >= 3:
        return parts[2].strip()[:60]
    return ""

def party_dbs(desc2):
    # take the human-ish name: words before bank name keyword
    m = re.search(r"(NEFTIN|NEFT|RTGS)\s+\S+\s+(.*?)\s+(KOTAK|DEUSTCHE|DEUTSCHE|HSBC|HDFC|ICICI|BANK OF AMERICA|STANDARD CHARTERED|FEDERAL|YES BANK|STATE BANK|CITI|BASSEIN)", desc2, re.I)
    if m:
        return m.group(2).strip()[:60]
    return desc2.strip()[:60]

